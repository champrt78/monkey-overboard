"""Generate STATUS.md and docs/tasks.json from the project tracker.

Reads PLAN.md (or docs/TODO.md if absent), merges tracker state into
docs/tasks.json without dropping anything it does not own, and renders
STATUS.md with the latest gate and cached CI verdicts.

Usage:
    python tools/status.py <project_path> [--write] [--json]

Without --write it prints what it would write and changes nothing.
"""
import json
import os
import re
import sys
import tempfile
from datetime import datetime, timezone

VALID_STATUSES = ("todo", "doing", "done")
DEFAULT_PERCENTS = {"done": 100, "doing": 50, "todo": 0}
TODO_HEADINGS = ("now", "next", "later / ideas", "blocked", "done")
SECTION_STATUS = {"now": "doing", "done": "done"}
STATUS_MARKER = "<!-- generated by tools/status.py; do not edit -->"

CHECK_ITEM_RE = re.compile(r"^\s*[-*]\s+\[( |x|X)\]\s+(?P<rest>.+)$")
PLAN_ITEM_RE = re.compile(r"^(?P<id>[A-Za-z]+-\d+)\s+(?P<title>.+)$")
STATUS_TAG_RE = re.compile(r"\(status:\s*(?P<status>todo|doing|done)\)\s*$")
HEADING_RE = re.compile(r"^\s{0,3}#{1,6}\s+(?P<text>.+?)\s*#*\s*$")


class TrackerError(Exception):
    pass


def now_utc():
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _read_text(path):
    with open(path, "r", encoding="utf-8") as handle:
        return handle.read()


def _dedupe(items):
    seen = {}
    out = []
    for item in items:
        base = item["id"]
        if base not in seen:
            seen[base] = 1
            item["id"] = base
        else:
            seen[base] += 1
            item["id"] = "{}-{}".format(base, seen[base])
        out.append(item)
    return out


def slugify(title):
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return slug or "task"


def parse_plan(text):
    """Parse PLAN.md items of the form '- [ ] P-12 Title (status: doing)'."""
    items = []
    for line in text.splitlines():
        m = CHECK_ITEM_RE.match(line)
        if not m:
            continue
        rest = m.group("rest").strip()
        im = PLAN_ITEM_RE.match(rest)
        if not im:
            continue
        title = im.group("title").strip()
        checked = m.group(1) in ("x", "X")
        tag = STATUS_TAG_RE.search(title)
        if tag:
            title = title[: tag.start()].strip()
        if checked:
            status = "done"
        elif tag:
            status = tag.group("status")
        else:
            status = "todo"
        items.append({"id": im.group("id"), "title": title, "status": status})
    return _dedupe(items)


def parse_todo(text):
    """Parse '- [ ]' / '- [x]' items under the Now, Next, Later / Ideas,
    Blocked and Done headings of docs/TODO.md."""
    items = []
    section = None
    for line in text.splitlines():
        h = HEADING_RE.match(line)
        if h:
            name = h.group("text").lower()
            section = name if name in TODO_HEADINGS else None
            continue
        m = CHECK_ITEM_RE.match(line)
        if not m or section is None:
            continue
        title = m.group("rest").strip()
        checked = m.group(1) in ("x", "X")
        status = "done" if checked else SECTION_STATUS.get(section, "todo")
        items.append({"id": slugify(title), "title": title, "status": status})
    return _dedupe(items)


def parse_tracker(project):
    """Return the tracker items for a project: PLAN.md if present, else
    docs/TODO.md. Raises TrackerError if neither exists."""
    plan = os.path.join(project, "PLAN.md")
    todo = os.path.join(project, "docs", "TODO.md")
    if os.path.isfile(plan):
        return parse_plan(_read_text(plan))
    if os.path.isfile(todo):
        return parse_todo(_read_text(todo))
    raise TrackerError(
        "no tracker found in '{}': expected PLAN.md or docs/TODO.md".format(project)
    )


def load_existing_tasks(project):
    """Return the tasks list from docs/tasks.json, or [] if absent.
    Raises TrackerError if the file exists but is not usable."""
    path = os.path.join(project, "docs", "tasks.json")
    if not os.path.isfile(path):
        return []
    try:
        data = json.loads(_read_text(path))
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise TrackerError("docs/tasks.json is not valid JSON: {}".format(exc))
    tasks = data.get("tasks") if isinstance(data, dict) else None
    if not isinstance(tasks, list):
        raise TrackerError("docs/tasks.json has no tasks list")
    return [t for t in tasks if isinstance(t, dict)]


def build_tasks(items, existing, now):
    """Merge tracker items over the existing tasks.json entries.

    Preserves existing ids, created_at and any fields the tool does not
    own; refreshes status, updated_at and (for done items) completed_at;
    fills completion_percent with 100/50/0 unless already set; keeps
    entries missing from the tracker and marks them "stale": true.
    """
    existing_by_id = {}
    for task in existing:
        tid = task.get("id")
        if isinstance(tid, str) and tid:
            existing_by_id[tid] = task

    merged = []
    seen_ids = set()
    for item in items:
        prev = existing_by_id.get(item["id"])
        if prev is not None:
            task = dict(prev)
        else:
            task = {
                "id": item["id"],
                "title": item["title"],
                "status": None,
                "completion_percent": None,
                "description": item["title"],
                "created_at": now,
                "updated_at": None,
                "subtasks": [],
            }
        task.pop("stale", None)
        task["id"] = item["id"]
        task["title"] = item["title"]
        task["status"] = item["status"]
        task["updated_at"] = now
        if not isinstance(task.get("completion_percent"), (int, float)) or isinstance(
            task.get("completion_percent"), bool
        ):
            task["completion_percent"] = DEFAULT_PERCENTS[item["status"]]
        if item["status"] == "done" and not task.get("completed_at"):
            task["completed_at"] = now
        merged.append(task)
        seen_ids.add(item["id"])

    for task in existing:
        tid = task.get("id")
        if isinstance(tid, str) and tid and tid not in seen_ids:
            task = dict(task)
            task["stale"] = True
            merged.append(task)
    return merged


def counts(tasks):
    result = {status: 0 for status in VALID_STATUSES}
    result["stale"] = 0
    for task in tasks:
        status = task.get("status")
        if status in result:
            result[status] += 1
        if task.get("stale"):
            result["stale"] += 1
    return result


def latest_gate_verdict(project):
    """Return (verdict, relative path) from the newest qa/gate/gate-*.txt,
    or None if there is no gate output."""
    gate_dir = os.path.join(project, "qa", "gate")
    if not os.path.isdir(gate_dir):
        return None
    files = [
        name
        for name in os.listdir(gate_dir)
        if name.startswith("gate-") and name.endswith(".txt")
    ]
    if not files:
        return None
    newest = max(files, key=lambda n: os.path.getmtime(os.path.join(gate_dir, n)))
    path = os.path.join(gate_dir, newest)
    for line in reversed(_read_text(path).splitlines()):
        line = line.strip()
        if line.startswith("GATE:"):
            return line[len("GATE:"):].strip(), "qa/gate/{}".format(newest)
    return None


def cached_ci_verdict(project):
    """Return the cached CI verdict from qa/ci.json, or None."""
    path = os.path.join(project, "qa", "ci.json")
    if not os.path.isfile(path):
        return None
    try:
        data = json.loads(_read_text(path))
    except (json.JSONDecodeError, UnicodeDecodeError):
        return None
    if isinstance(data, dict) and isinstance(data.get("verdict"), str):
        return data["verdict"]
    return None


def render_status(project, tasks, now):
    lines = [STATUS_MARKER, ""]
    lines.append("# STATUS - {}".format(os.path.basename(os.path.normpath(project))))
    lines.append("")
    lines.append("Generated: {} (UTC)".format(now))
    lines.append("")
    gate = latest_gate_verdict(project)
    if gate:
        lines.append("- Gate: {} ({})".format(gate[0], gate[1]))
    ci = cached_ci_verdict(project)
    if ci:
        lines.append("- CI: {} (qa/ci.json)".format(ci))
    if gate or ci:
        lines.append("")
    c = counts(tasks)
    lines.append("## Counts")
    lines.append("")
    lines.append("- done: {}".format(c["done"]))
    lines.append("- doing: {}".format(c["doing"]))
    lines.append("- todo: {}".format(c["todo"]))
    lines.append("- stale: {}".format(c["stale"]))
    lines.append("")
    for heading, status in (("## Doing", "doing"), ("## Todo", "todo")):
        lines.append(heading)
        lines.append("")
        entries = [t for t in tasks if t.get("status") == status]
        if entries:
            for t in entries:
                lines.append("- {} {}".format(t.get("id"), t.get("title", "")))
        else:
            lines.append("(none)")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def atomic_write(path, text):
    directory = os.path.dirname(path) or "."
    if not os.path.isdir(directory):
        os.makedirs(directory)
    fd, tmp = tempfile.mkstemp(prefix=".status-", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def run(project, now=None):
    """Build the two output files. Returns (outputs, meta) where outputs
    maps absolute path -> text."""
    now = now or now_utc()
    items = parse_tracker(project)
    tasks = build_tasks(items, load_existing_tasks(project), now)
    status_text = render_status(project, tasks, now)
    tasks_text = json.dumps({"tasks": tasks}, indent=2) + "\n"
    outputs = {
        os.path.join(project, "STATUS.md"): status_text,
        os.path.join(project, "docs", "tasks.json"): tasks_text,
    }
    meta = {
        "counts": counts(tasks),
        "gate": latest_gate_verdict(project),
        "ci": cached_ci_verdict(project),
    }
    return outputs, meta


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    write = False
    as_json = False
    paths = []
    for arg in argv:
        if arg == "--write":
            write = True
        elif arg == "--json":
            as_json = True
        else:
            paths.append(arg)

    if len(paths) != 1:
        sys.stderr.write(
            "usage: python tools/status.py <project_path> [--write] [--json]\n"
        )
        if as_json:
            print(
                json.dumps(
                    {"ok": False, "error": "usage: expected exactly one project path"}
                )
            )
        return 2
    project = os.path.abspath(paths[0])
    if not os.path.isdir(project):
        sys.stderr.write("error: '{}' is not a directory\n".format(paths[0]))
        if as_json:
            print(
                json.dumps({"ok": False, "error": "not a directory: {}".format(paths[0])})
            )
        return 1

    try:
        outputs, meta = run(project)
    except TrackerError as exc:
        sys.stderr.write("error: {}\n".format(exc))
        if as_json:
            print(json.dumps({"ok": False, "error": str(exc)}))
        return 1

    if write:
        for path, text in outputs.items():
            atomic_write(path, text)
        action = "wrote"
    else:
        action = "would write"

    if as_json:
        payload = {
            "ok": True,
            "project": project,
            "action": action,
            "counts": meta["counts"],
            "gate": list(meta["gate"]) if meta["gate"] else None,
            "ci": meta["ci"],
            "files": {
                os.path.relpath(path, project).replace(os.sep, "/"): text
                for path, text in outputs.items()
            },
        }
        print(json.dumps(payload))
    else:
        for path, text in outputs.items():
            rel = os.path.relpath(path, project).replace(os.sep, "/")
            print("{} {}:".format(action, rel))
            sys.stdout.write(text)
            if not text.endswith("\n"):
                print()
    return 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")
    sys.exit(main())
